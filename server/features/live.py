"""Real-event feature extraction for the live scoring path -- the
real-telemetry counterpart to `eval/features.py`, which only ever runs
against `SimulatedSession` objects. Same signal registry, same
window-sealing discipline; a different data source (real stored events,
Postgres row dicts, not `RawEvent` dataclasses generated by the
simulator) and a different normalization population (a session's *own*
already-closed views so far, recomputed fresh at every trigger per §9.2:
"Features are recomputed from the window at each trigger, not
incrementally folded... removes online/offline divergence at the root").

Deliberately kept inside `server/features/` (not `eval/`, which depends
on `server/features/` and would create a cycle if this imported from it)
even though it duplicates `eval/features.py`'s three-line signal-registry
merge -- the alternative is a real circular import between the two
independent root packages.

**Signals genuinely unavailable for real sessions, not a bug:**
`early_direction_bias` and `direction_lock_in_speed`
(`signals_directional.py`) need `accept_pos`/`reject_pos` -- real
on-screen coordinates for the item's own action region and the next
item's card. The current SDK telemetry schema (§7.2) has no event
carrying DOM element positions, so both are always `None` here. This is
the same "missing signal -> None, never synthesized" contract those
signals were built with; the live path simply has fewer available
signals than the simulator does, honestly.
"""
from __future__ import annotations

from dataclasses import dataclass

from server.features.labels import is_fast_skip
from server.features.mode import COMPARISON_WINDOW_MS, QuerySubmission, is_query_active
from server.features.normalize import z_score
from server.features.signals import SIGNAL_REGISTRY, ItemContext
from server.features.signals_directional import DIRECTIONAL_SIGNAL_REGISTRY
from server.features.signals_gate1 import GATE1_SIGNAL_REGISTRY
from server.features.window_spec import CommitmentEvent, RawEvent, seal_window_for_view

ALL_SIGNALS = {**SIGNAL_REGISTRY, **GATE1_SIGNAL_REGISTRY, **DIRECTIONAL_SIGNAL_REGISTRY}


@dataclass(frozen=True)
class LiveView:
    """One canonical, already-closed real view -- the subset of
    `server.features.item_view.ItemView` plus the catalog context this
    module needs that the view boundary computation itself doesn't
    carry."""

    item_id: str
    surface: str
    mode: str
    start: float
    end: float
    category: str | None
    near_substitute_set_id: str | None


def _raw_events_from_rows(rows: list[dict]) -> list[RawEvent]:
    return [
        RawEvent(t=r["ts_mono"], type=r["type"], item_id=r["payload"].get("item_id"), surface=r["surface"], payload=r["payload"])
        for r in rows
    ]


def _commitment_events_from_rows(rows: list[dict]) -> list[CommitmentEvent]:
    types = {"cart_add", "wishlist", "checkout_start"}
    out = []
    for r in rows:
        if r["type"] in types and r["payload"].get("item_id"):
            out.append(CommitmentEvent(t=r["ts_mono"], item_id=r["payload"]["item_id"], type=r["type"]))
    return out


def _active_query_token_count(rows: list[dict], t: float) -> int | None:
    queries = sorted(
        (QuerySubmission(submitted_at=r["ts_mono"], query=r["payload"].get("query", "")) for r in rows if r["type"] == "search"),
        key=lambda q: q.submitted_at,
    )
    active = next((q for q in reversed(queries) if is_query_active(t, q)), None)
    if active is None:
        return None
    return len(active.query.split())


def extract_session_features(
    event_rows: list[dict],
    views: list[LiveView],
    pointer_type: str = "mouse",
) -> list[dict[str, float | None]]:
    """One normalized-signal dict per view in `views` (same order),
    computed against the *real* stored event log. Population for
    z-scoring within (mode, surface) is every view in `views` sharing
    that stratum, including future ones in this list -- for a batch call
    over a session's whole history so far that's correct (mirrors
    eval/features.py); a live caller that wants strictly causal
    normalization should only pass views up to and including the
    trigger."""
    events = _raw_events_from_rows(event_rows)
    commitment_events = _commitment_events_from_rows(event_rows)

    raw_by_view: list[dict[str, float | None]] = []
    for i, view in enumerate(views):
        earlier = views[:i]
        same_item_earlier = [v for v in earlier if v.item_id == view.item_id]

        near_substitute_coview_count = None
        if view.near_substitute_set_id is not None:
            window_start = view.start - COMPARISON_WINDOW_MS
            near_substitute_coview_count = sum(
                1
                for v in earlier
                if v.near_substitute_set_id == view.near_substitute_set_id
                and v.item_id != view.item_id
                and window_start <= v.start <= view.start
            )

        ctx = ItemContext(
            item_id=view.item_id,
            surface=view.surface,
            mode=view.mode,
            pointer_type=pointer_type,
            category=view.category,
            prior_view_starts_for_item=tuple(v.start for v in same_item_earlier),
            prior_view_categories=tuple(v.category for v in earlier if v.category is not None),
            active_query_token_count=_active_query_token_count(event_rows, view.start),
            near_substitute_coview_count=near_substitute_coview_count,
            accept_pos=None,  # not available from real telemetry -- see module docstring
            reject_pos=None,
        )
        window = seal_window_for_view(view.start, view.end, view.item_id, commitment_events)
        raw = {name: fn(events, window, ctx) for name, fn in ALL_SIGNALS.items()}
        raw_by_view.append(raw)

    stratum_population: dict[tuple[str, str], dict[str, list[float]]] = {}
    for view, raw in zip(views, raw_by_view):
        bucket = stratum_population.setdefault((view.mode, view.surface), {name: [] for name in ALL_SIGNALS})
        for name, value in raw.items():
            if value is not None:
                bucket[name].append(value)

    normalized_by_view = []
    for view, raw in zip(views, raw_by_view):
        population = stratum_population[(view.mode, view.surface)]
        normalized_by_view.append({name: z_score(v, population[name]) if v is not None else None for name, v in raw.items()})
    return normalized_by_view


def view_is_fast_skip(view: LiveView, all_views: list[LiveView], commitment_events: list[CommitmentEvent]) -> bool:
    other_starts = [v.start for v in all_views if v.item_id == view.item_id and v is not view]
    return is_fast_skip(
        view_duration_ms=view.end - view.start,
        item_id=view.item_id,
        view_start=view.start,
        commitment_events=commitment_events,
        other_view_starts_for_item=other_starts,
    )
